#!/usr/bin/env bash
# Replace the public Wazuh lab defaults with generated passwords.
#
#   scripts/rotate-passwords.sh           fresh lab (no containers yet): run before `make up`
#   scripts/rotate-passwords.sh --apply   running lab: also push the new passwords to it
#
# Rotates the indexer `admin` and `kibanaserver` users and the `wazuh-wui` API user.
# Writes (all git-ignored):
#   stack/secrets/internal_users.yml  indexer users, bcrypt-hashed by the indexer's own hash.sh
#   stack/secrets/wazuh.yml           dashboard -> Wazuh API connection
#   .env                              the three passwords + the paths of the two files above
# The committed files under stack/config/ keep the documented upstream defaults.
# PowerShell equivalent: scripts/rotate-passwords.ps1. Procedure: SECURITY.md.
set -euo pipefail
export MSYS_NO_PATHCONV=1   # Git Bash: do not rewrite /usr/share/... container paths

cd "$(dirname "$0")/.."

APPLY=0
case "${1:-}" in
  "") ;;
  --apply) APPLY=1 ;;
  -h|--help) sed -n '2,13p' "$0"; exit 0 ;;
  *) echo "unknown option: $1 (see --help)" >&2; exit 2 ;;
esac

SECRETS=stack/secrets
INDEXER_TOOLS=/usr/share/wazuh-indexer/plugins/opensearch-security/tools
INDEXER_CERTS=/usr/share/wazuh-indexer/config/certs
JAVA_HOME_IN_IMAGE=/usr/share/wazuh-indexer/jdk

[ -f .env ] || cp .env.example .env
WAZUH_VERSION="$(sed -n 's/^WAZUH_VERSION=//p' .env | tail -n1 | tr -d '\r')"
INDEXER_IMAGE="wazuh/wazuh-indexer:${WAZUH_VERSION:-4.14.9}"

if [ "$APPLY" -eq 0 ] && [ -n "$(docker compose ps -q wazuh.indexer 2>/dev/null)" ]; then
  echo "The lab is running. Use --apply to rotate it in place, or 'make reset' first." >&2
  exit 1
fi

gen_password() {
  # 30 random alphanumerics as xxxxxxxxxx.xxxxxxxxxx-xxxxxxxxxx (~178 bits).
  # Upper, lower, digit and symbol satisfy the Wazuh API password policy; "." and "-"
  # are safe in .env, YAML, sed and unquoted shell expansions in the upstream images.
  local p
  while :; do
    p="$(head -c 1024 /dev/urandom | LC_ALL=C tr -dc 'A-Za-z0-9')"
    p="${p:0:10}.${p:10:10}-${p:20:10}"
    if [ "${#p}" -eq 32 ] && [[ $p =~ [A-Z] && $p =~ [a-z] && $p =~ [0-9] ]]; then
      printf '%s' "$p"
      return
    fi
  done
}

hash_password() {
  # The password reaches the container through the environment, never a command line.
  local h
  h="$(PW="$1" docker run --rm -e PW -e OPENSEARCH_JAVA_HOME="$JAVA_HOME_IN_IMAGE" \
        --entrypoint bash "$INDEXER_IMAGE" "$INDEXER_TOOLS/hash.sh" -env PW | tail -n1 | tr -d '\r')"
  # shellcheck disable=SC2016  # literal "$2y$": the bcrypt prefix, not a variable
  if [[ $h != '$2'[aby]'$'* ]]; then
    echo "hash.sh did not return a bcrypt hash (got: ${h:0:20}...)" >&2
    exit 1
  fi
  printf '%s' "$h"
}

set_env() {
  # Replace KEY=... in .env (keeping its position) or append it.
  awk -v k="$1" -v v="$2" '
    index($0, k "=") == 1 { print k "=" v; done = 1; next }
    { print }
    END { if (!done) print k "=" v }
  ' .env > .env.tmp
  mv .env.tmp .env
}

echo "Generating passwords and hashing them with $INDEXER_IMAGE ..."
INDEXER_PASSWORD="$(gen_password)"
DASHBOARD_PASSWORD="$(gen_password)"
API_PASSWORD="$(gen_password)"
ADMIN_HASH="$(hash_password "$INDEXER_PASSWORD")"
DASHBOARD_HASH="$(hash_password "$DASHBOARD_PASSWORD")"

mkdir -p "$SECRETS"
# Only the two users the lab needs. The upstream demo users (kibanaro, logstash,
# readall, snapshotrestore) have public passwords and are left out on purpose.
{
  printf '%s\n' '---' \
    '# Generated by scripts/rotate-passwords.sh. Git-ignored: never commit.' \
    '_meta:' '  type: "internalusers"' '  config_version: 2' ''
  printf 'admin:\n  hash: "%s"\n  reserved: true\n  backend_roles:\n  - "admin"\n  description: "Lab admin user"\n\n' \
    "$ADMIN_HASH"
  printf 'kibanaserver:\n  hash: "%s"\n  reserved: true\n  description: "Wazuh dashboard server user"\n' \
    "$DASHBOARD_HASH"
} > "$SECRETS/internal_users.yml"

{
  printf '%s\n' '# Generated by scripts/rotate-passwords.sh. Git-ignored: never commit.' \
    'hosts:' '  - 1513629884013:' '      url: "https://wazuh.manager"' '      port: 55000' \
    '      username: wazuh-wui'
  printf '      password: "%s"\n      run_as: true\n' "$API_PASSWORD"
} > "$SECRETS/wazuh.yml"

set_env INDEXER_PASSWORD "$INDEXER_PASSWORD"
set_env DASHBOARD_PASSWORD "$DASHBOARD_PASSWORD"
set_env API_PASSWORD "$API_PASSWORD"
set_env INDEXER_USERS_FILE "./$SECRETS/internal_users.yml"
set_env DASHBOARD_API_CONFIG "./$SECRETS/wazuh.yml"
chmod 600 .env 2>/dev/null || true

echo "Wrote $SECRETS/internal_users.yml, $SECRETS/wazuh.yml and .env"

if [ "$APPLY" -eq 1 ]; then
  # The indexer reads internal_users.yml only when its security index is first created;
  # on a running lab the new users are loaded with securityadmin (admin client certificate).
  echo "Recreating the indexer with the new users file ..."
  # --force-recreate: on a second rotation the mounted path is unchanged, so compose would not
  docker compose up -d --force-recreate --wait wazuh.indexer
  docker compose exec -T -e JAVA_HOME="$JAVA_HOME_IN_IMAGE" wazuh.indexer bash \
    "$INDEXER_TOOLS/securityadmin.sh" -t internalusers \
    -f /usr/share/wazuh-indexer/config/opensearch-security/internal_users.yml \
    -cacert "$INDEXER_CERTS/root-ca.pem" -cert "$INDEXER_CERTS/admin.pem" -key "$INDEXER_CERTS/admin-key.pem" \
    -h localhost -icl -nhnv
  # The manager re-applies API_PASSWORD (wazuh-wui) and the Filebeat password at every
  # start; the dashboard rebuilds its keystore. Recreating them picks up the new .env.
  echo "Recreating the manager and the dashboard ..."
  docker compose up -d --wait
  echo "Done. Check with: python scripts/lab_status.py"
else
  echo "Next: make up   (or: docker compose up -d --build)"
fi
echo "Dashboard login: admin / the INDEXER_PASSWORD value in .env"
