#!/usr/bin/env bash
# real-db-01: create the PostgreSQL cluster on first start, load the schema and the FAKE
# seed, set the lab role passwords from the real-secrets volume, start the server.
set -euo pipefail

SECRETS=/run/lab-secrets
PG_VERSION="$(ls /usr/lib/postgresql)"
CONF_DIR="/etc/postgresql/${PG_VERSION}/main"

if [ ! -d "$CONF_DIR" ]; then
  pg_createcluster --locale C.UTF-8 "$PG_VERSION" main >/dev/null
  cp /etc/insurco/postgres/insurco.conf "$CONF_DIR/conf.d/insurco.conf"
  cp /etc/insurco/postgres/pg_hba.conf "$CONF_DIR/pg_hba.conf"
  pg_ctlcluster "$PG_VERSION" main start
  su postgres -c "psql -q -v ON_ERROR_STOP=1" <<'SQL'
CREATE DATABASE insurco;
\c insurco
CREATE EXTENSION pgaudit;
-- Not audited: loading the seed (each foreign-key check is an internal read: ~3000 lines)
SET pgaudit.log = 'none';
\i /etc/insurco/postgres/schema.sql
\i /etc/insurco/postgres/seed.sql
SQL
  echo "[real-db] cluster ${PG_VERSION}/main created, FAKE seed loaded"
else
  pg_ctlcluster "$PG_VERSION" main start
fi

# Passwords: per lab, generated by real-secrets. Sent on stdin, never on a command line.
{
  for pair in portal_app:db-portal svc_reporting:db-reporting lab_analyst:db-analyst; do
    printf "ALTER ROLE %s PASSWORD '%s';\n" "${pair%%:*}" "$(cat "$SECRETS/${pair#*:}")"
  done
} | su postgres -c "psql -q -v ON_ERROR_STOP=1 -d insurco" >/dev/null
echo "[real-db] PostgreSQL ${PG_VERSION} + pgaudit listening on 5432"
