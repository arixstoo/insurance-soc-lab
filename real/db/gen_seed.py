#!/usr/bin/env python3
"""Write the seed dataset of real-db-01 as SQL (COPY blocks) on stdout.

Every row is FAKE: names from Faker (seeded, so every build produces the same rows),
e-mail addresses on the reserved example.* domains, no phone number, no national id,
no bank account. Run at image build time (real/db/Dockerfile), never against real data.

    python gen_seed.py > seed.sql
"""

from __future__ import annotations

import datetime as dt
import random
import sys

from faker import Faker

SEED = 2026
COUNTS = {"clients": 800, "policies": 1200, "claims": 600, "payments": 900, "beneficiaries": 500}
CITIES = ["Alger", "Oran", "Constantine", "Annaba", "Blida", "Setif", "Tlemcen", "Bejaia"]
PRODUCTS = ["motor", "home", "health", "travel", "life"]
CLAIM_KINDS = ["collision", "theft", "water damage", "fire", "hospital stay", "lost luggage"]
RELATIONS = ["spouse", "child", "parent", "sibling"]


def copy_block(table: str, columns: list[str], rows: list[list[object]]) -> str:
    def cell(value: object) -> str:
        text = str(value)
        return text.replace("\\", "\\\\").replace("\t", " ").replace("\n", " ")

    lines = [f"COPY {table} ({', '.join(columns)}) FROM stdin;"]
    lines += ["\t".join(cell(v) for v in row) for row in rows]
    lines.append("\\.")
    return "\n".join(lines) + "\n"


def generate(seed: int = SEED) -> str:
    fake = Faker("fr_FR")
    fake.seed_instance(seed)
    rng = random.Random(seed)
    day0 = dt.date(2024, 1, 1)

    clients = [[i, fake.name(), fake.date_of_birth(minimum_age=18, maximum_age=85), fake.safe_email(),
                rng.choice(CITIES), day0 + dt.timedelta(days=rng.randrange(700))]
               for i in range(1, COUNTS["clients"] + 1)]
    policies = [[i, rng.randrange(1, COUNTS["clients"] + 1), rng.choice(PRODUCTS),
                 f"{rng.uniform(8000, 250000):.2f}", day0 + dt.timedelta(days=rng.randrange(700)),
                 rng.choices(["active", "lapsed", "cancelled"], [8, 1, 1])[0]]
                for i in range(1, COUNTS["policies"] + 1)]
    claims = [[i, rng.randrange(1, COUNTS["policies"] + 1), day0 + dt.timedelta(days=rng.randrange(700)),
               rng.choice(CLAIM_KINDS), f"{rng.uniform(5000, 1500000):.2f}",
               rng.choices(["open", "approved", "rejected", "paid"], [3, 2, 1, 4])[0]]
              for i in range(1, COUNTS["claims"] + 1)]
    payments = [[i, rng.randrange(1, COUNTS["claims"] + 1), day0 + dt.timedelta(days=rng.randrange(700)),
                 f"{rng.uniform(5000, 900000):.2f}", rng.choice(["transfer", "cheque"])]
                for i in range(1, COUNTS["payments"] + 1)]
    beneficiaries = [[i, rng.randrange(1, COUNTS["policies"] + 1), fake.name(), rng.choice(RELATIONS)]
                     for i in range(1, COUNTS["beneficiaries"] + 1)]

    return "".join([
        f"-- real-db-01 seed: FAKE data generated by gen_seed.py (Faker, seed {SEED}). Not real people.\n",
        copy_block("clients", ["id", "full_name", "birth_date", "email", "city", "created_on"], clients),
        copy_block("policies", ["id", "client_id", "product", "premium_dzd", "start_date", "status"], policies),
        copy_block("claims", ["id", "policy_id", "claim_date", "kind", "amount_dzd", "status"], claims),
        copy_block("payments", ["id", "claim_id", "paid_on", "amount_dzd", "method"], payments),
        copy_block("beneficiaries", ["id", "policy_id", "full_name", "relationship"], beneficiaries),
    ])


if __name__ == "__main__":
    sys.stdout.write(generate())
